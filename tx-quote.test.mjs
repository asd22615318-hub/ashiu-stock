const at=Date.parse('2026-10-29T09:00:00Z');
const q=(symbol,price,date='20261029',time='170000')=>({SymbolID:symbol,CLastPrice:String(price),CDate:date,CTime:time,CRefPrice:'46000',CDiff:'100',CDiffRate:'0.22'});
